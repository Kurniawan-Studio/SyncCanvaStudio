/**
 * useP2PSync — Core P2P collaboration engine for SyncCanvas Studio.
 *
 * Responsibilities:
 *  - Manage a single Y.Doc shared across whiteboard + markdown + code.
 *  - Persist locally via IndexedDB (offline-first).
 *  - Sync across peers via WebRTC (y-webrtc) with optional encryption password.
 *  - Provide per-user undo/redo (UndoManager scoped to local origin only).
 *  - Expose live presence (multi-cursor + selection) via y-protocols Awareness.
 *  - Guarantee deterministic cleanup to prevent WebRTC memory leaks.
 */

import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import * as Y from 'yjs';
import { WebrtcProvider } from 'y-webrtc';
import { IndexeddbPersistence } from 'y-indexeddb';
import type { Awareness } from 'y-protocols/awareness';

/** Shared workspace field identifiers (must match keys used in App). */
export type WorkspaceField = 'markdown' | 'code';

/** Normalized whiteboard coordinate (0..1 of canvas width/height). */
export interface PeerCursor {
  x: number;
  y: number;
}

/** Text selection inside an editable field. */
export interface PeerSelection {
  start: number;
  end: number;
  field: WorkspaceField;
}

/** A remote participant as seen through awareness. */
export interface PeerUser {
  clientId: number;
  name: string;
  color: string;
  cursor: PeerCursor | null;
  selection: PeerSelection | null;
}

/** Public connection status snapshot. */
export interface P2PSyncStatus {
  isConnected: boolean;
  isSynced: boolean;
  peerCount: number;
  error: string | null;
}

/** Per-user undo/redo availability. */
export interface UndoRedoState {
  canUndo: boolean;
  canRedo: boolean;
}

export interface UseP2PSyncOptions {
  /** Shared room identifier (e.g. generated by generateRoomId). */
  roomId: string;
  /** Optional passphrase used to encrypt the WebRTC channel. */
  password?: string;
  /** Local user identity broadcast to peers. */
  user: { name: string; color: string };
  /** Optional custom signaling server list (defaults to public servers). */
  signalingServers?: string[];
}

export interface UseP2PSyncResult {
  doc: Y.Doc;
  provider: WebrtcProvider | null;
  persistence: IndexeddbPersistence | null;
  awareness: Awareness | null;
  undoManager: Y.UndoManager | null;
  status: P2PSyncStatus;
  peers: PeerUser[];
  undoState: UndoRedoState;
  /** Wrap local mutations so UndoManager can group and revert them. */
  transact: (fn: () => void) => void;
  setLocalCursor: (cursor: PeerCursor | null) => void;
  setLocalSelection: (selection: PeerSelection | null) => void;
  undo: () => void;
  redo: () => void;
}

/** Public signaling endpoints (handshake only — payload flows P2P). */
const DEFAULT_SIGNALING_SERVERS: readonly string[] = [
  'wss://signaling.yjs.dev',
  'wss://y-webrtc-eu.fly.dev',
];

/** Curated palette for deterministic peer colors (Narka warm-muted set). */
export const USER_COLORS: readonly string[] = [
  '#B85450',
  '#C77844',
  '#A68A4E',
  '#7A8B5E',
  '#5E8B7E',
  '#5E7A8B',
  '#6B5E8B',
  '#8B5E7A',
  '#D6C6B8',
  '#6C6C6A',
];

/** Alphabet intentionally excludes look-alike characters (0/O, 1/I/L). */
const ROOM_ID_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

/**
 * Cryptographically strong room ID generator.
 * Length defaults to 8 — sufficient entropy for a short share code.
 */
export function generateRoomId(length = 8): string {
  const safeLength = Math.max(4, Math.min(32, Math.floor(length)));
  const bytes = new Uint8Array(safeLength);
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < safeLength; i += 1) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }
  let result = '';
  for (let i = 0; i < safeLength; i += 1) {
    result += ROOM_ID_ALPHABET[bytes[i] % ROOM_ID_ALPHABET.length];
  }
  return result;
}

/** Pick a peer color at random (used when creating a new identity). */
export function pickRandomUserColor(): string {
  return USER_COLORS[Math.floor(Math.random() * USER_COLORS.length)];
}

/** Top-level shared type keys — keep in sync with App and exporters. */
export const SHARED_KEYS = {
  markdown: 'markdown',
  code: 'code',
  strokes: 'strokes',
  strokesMeta: 'strokesMeta',
} as const;

interface LocalIdentityState {
  name: string;
  color: string;
  cursor: PeerCursor | null;
  selection: PeerSelection | null;
}

export function useP2PSync(options: UseP2PSyncOptions): UseP2PSyncResult {
  const { roomId, password, user, signalingServers } = options;

  // Stable Y.Doc per component mount.
  const [doc] = useState<Y.Doc>(() => new Y.Doc());

  const [provider, setProvider] = useState<WebrtcProvider | null>(null);
  const [persistence, setPersistence] = useState<IndexeddbPersistence | null>(null);
  const [awareness, setAwareness] = useState<Awareness | null>(null);
  const [undoManager, setUndoManager] = useState<Y.UndoManager | null>(null);

  const [status, setStatus] = useState<P2PSyncStatus>({
    isConnected: false,
    isSynced: false,
    peerCount: 0,
    error: null,
  });
  const [peers, setPeers] = useState<PeerUser[]>([]);
  const [undoState, setUndoState] = useState<UndoRedoState>({
    canUndo: false,
    canRedo: false,
  });

  // Latest local identity — read synchronously inside async effect setup.
  const localIdentityRef = useRef<LocalIdentityState>({
    name: user.name,
    color: user.color,
    cursor: null,
    selection: null,
  });
  localIdentityRef.current.name = user.name;
  localIdentityRef.current.color = user.color;

  // Serialize signaling config so effect deps are stable across renders.
  const signalingKey = useMemo(
    () => (signalingServers && signalingServers.length > 0 ? signalingServers.join('|') : ''),
    [signalingServers],
  );

  useEffect(() => {
    let cancelled = false;

    const serverList =
      signalingKey.length > 0 ? signalingKey.split('|') : [...DEFAULT_SIGNALING_SERVERS];

    // -------------------------------------------------------------
    // 1. Offline persistence (IndexedDB).
    // -------------------------------------------------------------
    let idb: IndexeddbPersistence;
    try {
      idb = new IndexeddbPersistence(`synccanvas-room-${roomId}`, doc);
    } catch (err) {
      setStatus((prev) => ({
        ...prev,
        error:
          err instanceof Error
            ? err.message
            : 'Failed to initialize offline persistence (IndexedDB).',
      }));
      return () => {
        /* nothing to clean */
      };
    }
    setPersistence(idb);

    idb.whenSynced
      .then(() => {
        if (cancelled) return;
        setStatus((prev) => ({ ...prev, isSynced: true }));
      })
      .catch((err: unknown) => {
        if (cancelled) return;
        setStatus((prev) => ({
          ...prev,
          error:
            err instanceof Error
              ? err.message
              : 'Offline persistence failed to synchronize.',
        }));
      });

    // -------------------------------------------------------------
    // 2. WebRTC provider (P2P sync + awareness).
    // -------------------------------------------------------------
    let rtcProvider: WebrtcProvider;
    try {
      rtcProvider = new WebrtcProvider(`synccanvas-room-${roomId}`, doc, {
        signaling: serverList,
        ...(password && password.length > 0 ? { password } : {}),
      });
    } catch (err) {
      setStatus((prev) => ({
        ...prev,
        error:
          err instanceof Error
            ? err.message
            : 'Failed to initialize WebRTC provider.',
      }));
      idb.destroy();
      return () => {
        /* nothing further to clean */
      };
    }
    setProvider(rtcProvider);
    setAwareness(rtcProvider.awareness);

    // Seed local awareness state so peers see us immediately.
    rtcProvider.awareness.setLocalStateField('user', {
      name: localIdentityRef.current.name,
      color: localIdentityRef.current.color,
    });
    rtcProvider.awareness.setLocalStateField('cursor', localIdentityRef.current.cursor);
    rtcProvider.awareness.setLocalStateField('selection', localIdentityRef.current.selection);

    // -------------------------------------------------------------
    // 3. Per-user UndoManager (only tracks origin === null).
    //    Remote updates flow in with origin === rtcProvider.
    // -------------------------------------------------------------
    const markdownText = doc.getText(SHARED_KEYS.markdown);
    const codeText = doc.getText(SHARED_KEYS.code);
    const strokesArray = doc.getArray<Y.Map<unknown>>(SHARED_KEYS.strokes);

    const um = new Y.UndoManager([markdownText, codeText, strokesArray], {
      captureTimeout: 400,
      trackedOrigins: new Set<unknown>([null]),
    });
    setUndoManager(um);

    // -------------------------------------------------------------
    // 4. Awareness → peers list.
    // -------------------------------------------------------------
    const handleAwarenessChange = (): void => {
      if (cancelled) return;
      const states = rtcProvider.awareness.getStates();
      const nextPeers: PeerUser[] = [];
      states.forEach((rawState, clientId) => {
        if (clientId === doc.clientID) return;
        const state = rawState as {
          user?: { name?: string; color?: string };
          cursor?: PeerCursor | null;
          selection?: PeerSelection | null;
        };
        nextPeers.push({
          clientId,
          name: state.user?.name ?? 'Anonymous',
          color: state.user?.color ?? '#64748b',
          cursor: state.cursor ?? null,
          selection: state.selection ?? null,
        });
      });
      setPeers(nextPeers);
      setStatus((prev) => ({
        ...prev,
        isConnected: nextPeers.length > 0,
        peerCount: nextPeers.length,
      }));
    };
    handleAwarenessChange();
    rtcProvider.awareness.on('change', handleAwarenessChange);

    // -------------------------------------------------------------
    // 5. Undo stack → react state.
    // -------------------------------------------------------------
    const refreshUndoState = (): void => {
      if (cancelled) return;
      setUndoState({ canUndo: um.canUndo(), canRedo: um.canRedo() });
    };
    refreshUndoState();
    um.on('stack-item-added', refreshUndoState);
    um.on('stack-item-popped', refreshUndoState);
    um.on('stack-cleared', refreshUndoState);

    // -------------------------------------------------------------
    // Cleanup — deterministic, leak-free.
    // -------------------------------------------------------------
    return () => {
      cancelled = true;

      rtcProvider.awareness.off('change', handleAwarenessChange);
      um.off('stack-item-added', refreshUndoState);
      um.off('stack-item-popped', refreshUndoState);
      um.off('stack-cleared', refreshUndoState);

      um.destroy();
      rtcProvider.destroy();
      idb.destroy();

      setProvider(null);
      setPersistence(null);
      setAwareness(null);
      setUndoManager(null);
      setPeers([]);
      setUndoState({ canUndo: false, canRedo: false });
      setStatus({ isConnected: false, isSynced: false, peerCount: 0, error: null });
    };
  }, [doc, roomId, password, signalingKey]);

  // Propagate local identity changes (name / color) to peers.
  useEffect(() => {
    if (!awareness) return;
    awareness.setLocalStateField('user', {
      name: user.name,
      color: user.color,
    });
  }, [awareness, user.name, user.color]);

  const setLocalCursor = useCallback(
    (cursor: PeerCursor | null): void => {
      localIdentityRef.current.cursor = cursor;
      if (awareness) {
        awareness.setLocalStateField('cursor', cursor);
      }
    },
    [awareness],
  );

  const setLocalSelection = useCallback(
    (selection: PeerSelection | null): void => {
      localIdentityRef.current.selection = selection;
      if (awareness) {
        awareness.setLocalStateField('selection', selection);
      }
    },
    [awareness],
  );

  const transact = useCallback(
    (fn: () => void): void => {
      doc.transact(fn, null);
    },
    [doc],
  );

  const undo = useCallback((): void => {
    undoManager?.undo();
  }, [undoManager]);

  const redo = useCallback((): void => {
    undoManager?.redo();
  }, [undoManager]);

  return {
    doc,
    provider,
    persistence,
    awareness,
    undoManager,
    status,
    peers,
    undoState,
    transact,
    setLocalCursor,
    setLocalSelection,
    undo,
    redo,
  };
}
